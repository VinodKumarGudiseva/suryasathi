import { solarAdvisorService } from './solarAdvisorService';
import { schemeKnowledgeService } from './schemeKnowledgeService';
import { buildAdvisorContext } from './advisorContext';
import { buildBedrockPayload, normalizeBedrockResponse } from './bedrockAdvisorAdapter';
import { SolarPlan, AdvisorContext } from '../types/solar';

/**
 * Test Suite: SuryaSathi AI Advisor & Scheme Knowledge Pipeline Audit
 */
async function runTests() {
  console.log('--- STARTING AI ADVISOR & KNOWLEDGE PIPELINE AUDIT ---');
  let passed = 0;
  let failed = 0;

  function assert(condition: boolean, testName: string, details?: string) {
    if (condition) {
      console.log(`✅ [PASS] ${testName}`);
      passed++;
    } else {
      console.error(`❌ [FAIL] ${testName}: ${details || 'Assertion failed'}`);
      failed++;
    }
  }

  // Mock Solar Plan context generated by calculation engine
  const mockPlan: Partial<SolarPlan> = {
    id: 'test-plan-456',
    location: {
      state: 'Maharashtra',
      city: 'Pune',
      discomName: 'MSEDCL',
    },
    monthlyConsumptionKwh: 310,
    monthlyBillAmount: 2650,
    recommendedSystemKw: 2.5,
    annualGenerationKwh: 3625,
    annualSavings: 23560,
    installationCost: 130000,
    subsidy: 78000,
    netInvestment: 52000,
    paybackYears: 2.2,
    co2ReductionKg: 2972,
    roofAnalysis: {
      suitability: 'Suitable',
      usableAreaSqM: 32.5,
      usableAreaSqFt: 350,
      confidence: 0.92,
      estimatedPanelCount: 14,
      estimatedCapacityKw: 3.2,
      factors: {
        estimatedUsableArea: '32.5 m²',
        obstructions: 'None/Minimal',
        shading: 'Minimal (Favorable)',
        orientation: 'Favorable (South/South-West)',
      },
      explanation: 'Optimal terrace space',
      source: 'ai_assisted_estimate',
    },
    billData: {
      provider: 'MSEDCL',
      monthlyConsumptionKwh: 310,
      billAmount: 2650,
      confidence: 0.95,
      extractedFieldsCount: 5,
      isUserConfirmed: true,
      source: 'extracted',
    },
  };

  // TEST 1: Sanitized Context Extraction (No PII leakage)
  try {
    const ctx = buildAdvisorContext(mockPlan);
    assert(
      ctx.state === 'Maharashtra' &&
      ctx.recommendedSystemKw === 2.5 &&
      ctx.estimatedSubsidy === 78000 &&
      ctx.netInvestment === 52000 &&
      ctx.roofSuitability === 'Suitable' &&
      ctx.roofConfidence === 0.92,
      'Context Builder maps SolarPlan fields faithfully without alteration'
    );
  } catch (err: any) {
    assert(false, 'Context Builder execution', err.message);
  }

  // TEST 2: Context without Plan (Graceful handling of null/undefined metrics)
  try {
    const emptyCtx = buildAdvisorContext(undefined);
    assert(
      emptyCtx.recommendedSystemKw === undefined &&
      emptyCtx.estimatedSubsidy === undefined,
      'Context Builder handles undefined plan cleanly without throwing'
    );
  } catch (err: any) {
    assert(false, 'Context Builder empty handling', err.message);
  }

  // TEST 3: Scheme Knowledge Semantic & Keyword Search
  try {
    const results = await schemeKnowledgeService.searchSchemeKnowledge('How much subsidy for 3 kw');
    assert(
      results.length > 0 &&
      results.some((r) => r.id === 'pm-surya-ghar-subsidy-slabs'),
      'Scheme Knowledge Base retrieves subsidy slab documentation for subsidy query'
    );
  } catch (err: any) {
    assert(false, 'Scheme Knowledge Service query', err.message);
  }

  // TEST 4: Scheme Knowledge Net Metering Query
  try {
    const netResults = await schemeKnowledgeService.searchSchemeKnowledge('bi-directional export meter discom');
    assert(
      netResults.length > 0 &&
      netResults.some((r) => r.id === 'net-metering-process'),
      'Scheme Knowledge Base retrieves net-metering regulations for bi-directional meter query'
    );
  } catch (err: any) {
    assert(false, 'Scheme Knowledge Net Metering query', err.message);
  }

  // TEST 5: Strict Grounding & Numerical Value Consistency (Subsidy)
  try {
    const res = await solarAdvisorService.askSolarAdvisor('What is my estimated subsidy?', mockPlan);
    assert(
      res.text.includes('78,000') &&
      res.text.includes('2.5 kW') &&
      res.sources !== undefined &&
      res.sources.length > 0 &&
      res.confidence! >= 0.90,
      'AI Advisor answers subsidy question using exact calculation engine value (₹78,000) and returns sources'
    );
  } catch (err: any) {
    assert(false, 'Subsidy question grounding', err.message);
  }

  // TEST 6: Strict Grounding for Financial Payback
  try {
    const res = await solarAdvisorService.askSolarAdvisor('What is my payback period and annual savings?', mockPlan);
    assert(
      res.text.includes('2.2 years') &&
      res.text.includes('23,560') &&
      res.text.includes('52,000'),
      'AI Advisor adheres strictly to calculation engine values for payback (2.2 years), savings (₹23,560), and net cost (₹52,000)'
    );
  } catch (err: any) {
    assert(false, 'Payback & savings grounding', err.message);
  }

  // TEST 7: Handling Missing Plan Context (Does NOT hallucinate numbers)
  try {
    const res = await solarAdvisorService.askSolarAdvisor('What is my payback period?');
    assert(
      res.text.includes('assessment') || res.text.includes('unavailable') || res.text.includes('typically'),
      'AI Advisor refuses to invent specific personalized payback when plan is unavailable'
    );
  } catch (err: any) {
    assert(false, 'Missing plan graceful handling', err.message);
  }

  // TEST 8: Rooftop Suitability Context Awareness
  try {
    const res = await solarAdvisorService.askSolarAdvisor('Is my terrace suitable for solar?', mockPlan);
    assert(
      res.text.includes('Suitable') &&
      res.text.includes('32.5 m²') &&
      res.text.includes('planning estimate'),
      'AI Advisor reports roof suitability, usable area, and disclaims AI estimate'
    );
  } catch (err: any) {
    assert(false, 'Rooftop suitability grounding', err.message);
  }

  // TEST 9: Prompt Template & Bedrock Payload Serialization
  try {
    const ctx = buildAdvisorContext(mockPlan);
    const bedrockPayload = buildBedrockPayload(
      'What documents do I need?',
      ctx,
      ['National Portal requires Electricity Bill, Aadhaar, Rooftop photo, Bank cheque']
    );
    assert(
      bedrockPayload.modelId.includes('claude-3-5-sonnet') &&
      bedrockPayload.messages.length > 0 &&
      bedrockPayload.inferenceConfig.temperature <= 0.3 &&
      bedrockPayload.system[0].text.includes('SINGLE SOURCE OF TRUTH'),
      'Bedrock payload generator creates valid structure with low temperature and strict system prompt'
    );
  } catch (err: any) {
    assert(false, 'Bedrock payload generation', err.message);
  }

  // TEST 10: Bedrock Response Normalizer
  try {
    const mockBedrockOutput = {
      output: {
        message: {
          content: [
            {
              text: 'You need an electricity bill, Aadhaar card, bank passbook, and rooftop photo under PM Surya Ghar guidelines.',
            },
          ],
        },
      },
    };
    const normalized = normalizeBedrockResponse(mockBedrockOutput);
    assert(
      normalized.sender === 'assistant' &&
      normalized.text.includes('electricity bill') &&
      normalized.confidence! >= 0.90 &&
      normalized.sources!.length > 0,
      'Bedrock response normalizer correctly parses Converse API response structure'
    );
  } catch (err: any) {
    assert(false, 'Bedrock normalizer test', err.message);
  }

  console.log(`\n--- AUDIT COMPLETE: ${passed} PASSED, ${failed} FAILED ---`);
  if (failed > 0) {
    process.exit(1);
  }
}

runTests().catch((e) => {
  console.error('Fatal test error:', e);
  process.exit(1);
});
